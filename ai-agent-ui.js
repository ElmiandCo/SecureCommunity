/* OneMuslim AI — transparent account labeling only. */
(() => {
  const AI_USERNAME = "onemuslim_ai";
  const STYLE_ID = "onemuslim-ai-badge-style";

  function installStyles() {
    if (document.getElementById(STYLE_ID)) return;
    const style = document.createElement("style");
    style.id = STYLE_ID;
    style.textContent = `
      .om-ai-badge{display:inline-flex;align-items:center;gap:4px;margin-left:7px;padding:2px 7px;border-radius:999px;background:linear-gradient(135deg,#0b4f88,#2aa5df);color:#fff;font-size:10px;font-weight:800;letter-spacing:.05em;text-transform:uppercase;vertical-align:middle;box-shadow:0 3px 10px rgba(16,102,164,.22)}
      .om-ai-badge::before{content:"✦";font-size:9px}
      .om-ai-post .post-head{position:relative}
      .om-ai-post .post-author b{display:inline-flex;align-items:center}
      .om-ai-post .post-author b::after{content:"AI ACCOUNT";margin-left:7px;color:#168bd0;font-size:9px;font-weight:800;letter-spacing:.06em}
      .om-ai-comment .comment-head b{display:inline-flex;align-items:center}
      .om-ai-comment .comment-head b::after{content:"AI";margin-left:6px;color:#168bd0;font-size:9px;font-weight:800;letter-spacing:.05em}
    `;
    document.head.appendChild(style);
  }

  function isAiAuthor(authorBlock) {
    return !!authorBlock && new RegExp(`@${AI_USERNAME}(?:\\b|$)`, "i").test(authorBlock.textContent || "");
  }

  function markFeed() {
    installStyles();
    document.querySelectorAll("#feed .post").forEach(post => {
      const author = post.querySelector(".post-author");
      if (!isAiAuthor(author)) return;
      post.classList.add("om-ai-post");
      const name = author?.querySelector("b");
      if (name && !name.querySelector(".om-ai-badge")) {
        const badge = document.createElement("span");
        badge.className = "om-ai-badge";
        badge.textContent = "AI";
        badge.title = "This account is operated by an AI agent.";
        name.appendChild(badge);
      }
    });

    document.querySelectorAll("#feed .comment").forEach(comment => {
      const head = comment.querySelector(".comment-head");
      if (!isAiAuthor(head)) return;
      comment.classList.add("om-ai-comment");
      const name = head?.querySelector("b");
      if (name && !name.querySelector(".om-ai-badge")) {
        const badge = document.createElement("span");
        badge.className = "om-ai-badge";
        badge.textContent = "AI";
        badge.title = "This comment was generated by OneMuslim AI.";
        name.appendChild(badge);
      }
    });

    document.querySelectorAll("#profilesGrid .profile-card").forEach(card => {
      if (!new RegExp(`@${AI_USERNAME}(?:\\b|$)`, "i").test(card.textContent || "")) return;
      card.classList.add("om-ai-post");
      const name = card.querySelector("h3");
      if (name && !name.querySelector(".om-ai-badge")) {
        const badge = document.createElement("span");
        badge.className = "om-ai-badge";
        badge.textContent = "AI";
        name.appendChild(badge);
      }
    });
  }

  const observer = new MutationObserver(markFeed);
  function start() {
    markFeed();
    const feed = document.getElementById("feed");
    const profiles = document.getElementById("profilesGrid");
    if (feed) observer.observe(feed, {childList:true, subtree:true});
    if (profiles) observer.observe(profiles, {childList:true, subtree:true});
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start, {once:true});
  else start();
})();
