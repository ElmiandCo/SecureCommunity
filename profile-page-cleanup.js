/* OneMuslim My Profile cleanup — keep only the My Profile title and real profile card. */
(function(){
  'use strict';

  function cleanup(){
    const page=document.getElementById('profilePage');
    const panel=document.getElementById('profilePanel');
    if(!page || !panel)return;

    // Keep the page title, but remove the redundant eyebrow and any other header content.
    const head=page.querySelector(':scope > .page-head');
    if(head){
      const title=head.querySelector('h2');
      if(title){
        title.textContent='My Profile';
        [...head.children].forEach(el=>{
          if(el!==title && !el.contains(title)) el.remove();
        });
        const wrapper=title.parentElement;
        if(wrapper!==head){
          head.innerHTML='';
          head.appendChild(title);
        }
      }else{
        head.innerHTML='<h2>My Profile</h2>';
      }
    }else{
      const newHead=document.createElement('div');
      newHead.className='page-head';
      newHead.innerHTML='<h2>My Profile</h2>';
      page.insertBefore(newHead,panel);
    }

    // app.js still renders the legacy profile summary into #profilePanel.
    // Keep only the real saved profile card generated by profile-view.js.
    panel.querySelectorAll(':scope > *').forEach(el=>{
      if(!el.classList.contains('om-my-profile-card')) el.remove();
    });
  }

  function init(){
    cleanup();
    const page=document.getElementById('profilePage');
    if(!page)return;
    if(!page.dataset.omProfileCleanupV5){
      page.dataset.omProfileCleanupV5='1';
      new MutationObserver(cleanup).observe(page,{childList:true,subtree:true});
    }
  }

  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);else init();
  window.OneMuslimProfilePageCleanup={render:cleanup};
})();
