/* OneMuslim My Profile cleanup — keep only the real profile card. */
(function(){
  'use strict';

  function cleanup(){
    const page=document.getElementById('profilePage');
    const panel=document.getElementById('profilePanel');
    if(!page || !panel)return;

    // The My Profile page should contain only the actual profile card.
    // Remove the legacy page-level "YOUR PRIVATE PROFILE / My Profile" header
    // instead of recreating it.
    page.querySelectorAll(':scope > .page-head').forEach(el=>el.remove());

    // app.js may render a legacy profile summary into #profilePanel.
    // Keep only the real saved profile card generated by the profile system.
    panel.querySelectorAll(':scope > *').forEach(el=>{
      if(!el.classList.contains('om-my-profile-card')) el.remove();
    });
  }

  function init(){
    cleanup();
    const page=document.getElementById('profilePage');
    if(!page)return;
    if(!page.dataset.omProfileCleanupV6){
      page.dataset.omProfileCleanupV6='1';
      new MutationObserver(cleanup).observe(page,{childList:true,subtree:true});
    }
  }

  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);else init();
  window.OneMuslimProfilePageCleanup={render:cleanup};
})();
